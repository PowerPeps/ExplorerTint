# Generates src\LinguistData.h from github-linguist data (MIT license):
# languages.yml, popular.yml, vendor.yml and documentation.yml, downloaded unless -Source points to a local copy.
param([string]$Source = "https://raw.githubusercontent.com/github-linguist/linguist/main/lib/linguist")

$ErrorActionPreference = "Stop"
$out = Join-Path $PSScriptRoot "..\src\LinguistData.h"

function Read-Source($name) {
    if ($Source -match '^https?://') { return (Invoke-WebRequest -UseBasicParsing "$Source/$name").Content -split "`n" }
    return Get-Content (Join-Path $Source $name) -Encoding UTF8
}

function Unquote($s) {
    $s = $s.Trim()
    if ($s.Length -ge 2 -and ($s[0] -eq '"' -or $s[0] -eq "'") -and $s[-1] -eq $s[0]) { $s = $s.Substring(1, $s.Length - 2) }
    return $s
}

function CString($s) { return 'L"' + $s.Replace('\', '\\').Replace('"', '\"') + '"' }

$langs = [ordered]@{}
$cur = $null; $list = $null
foreach ($line in (Read-Source "languages.yml")) {
    $line = $line.TrimEnd("`r")
    if ($line -match '^([^\s#-][^:]*):\s*$') {
        $cur = [ordered]@{ name = $Matches[1]; type = ""; color = ""; group = ""; extensions = @(); filenames = @() }
        $langs[$cur.name] = $cur; $list = $null
    } elseif ($cur -and $line -match '^  (type|color|group):\s*(.+)$') {
        $cur[$Matches[1]] = Unquote $Matches[2]; $list = $null
    } elseif ($cur -and $line -match '^  (extensions|filenames):\s*$') {
        $list = $Matches[1]
    } elseif ($cur -and $list -and $line -match '^  - (.+)$') {
        $cur[$list] += Unquote $Matches[1]
    } elseif ($line -match '^  \S') {
        $list = $null
    }
}

# Only programming and markup languages count in GitHub's statistics; a group counts as its parent.
$counted = @($langs.Values | Where-Object { $_.type -eq "programming" -or $_.type -eq "markup" })
$names = New-Object System.Collections.Generic.List[string]
$index = @{}
foreach ($l in $counted) {
    $target = if ($l.group -and $langs.Contains($l.group)) { $langs[$l.group] } else { $l }
    if (-not $index.ContainsKey($target.name)) { $index[$target.name] = $names.Count; $names.Add($target.name) }
}

# Uncounted languages keep their extensions (language 65535) so that, say, ".md" stays Markdown rather than
# becoming GCC Machine Description. Candidates for a key: primary extension first, then popular languages,
# then languages with more extensions and filenames (a stand-in for linguist's content heuristics).
$popular = @{}
Read-Source "popular.yml" | ForEach-Object { $_.TrimEnd("`r") } | Where-Object { $_ -match '^- ' } | ForEach-Object { $popular[(Unquote $_.Substring(2))] = $true }
$extensions = New-Object System.Collections.Generic.List[object]
$filenames = New-Object System.Collections.Generic.List[object]
foreach ($l in $langs.Values) {
    $isCounted = $l.type -eq "programming" -or $l.type -eq "markup"
    $target = if ($l.group -and $langs.Contains($l.group)) { $l.group } else { $l.name }
    $lang = if ($isCounted) { $index[$target] } else { 65535 }
    $rank = if ($popular.Contains($l.name)) { 0 } else { 1 }
    $i = 0
    foreach ($e in $l.extensions) { $extensions.Add([pscustomobject]@{ key = $e.ToLowerInvariant(); lang = $lang; primary = 2 * [int]($i -ne 0) + $rank; spread = -($l.extensions.Count + $l.filenames.Count); name = $l.name }); $i++ }
    foreach ($f in $l.filenames) { $filenames.Add([pscustomobject]@{ key = $f; lang = $lang; primary = $rank; spread = -($l.extensions.Count + $l.filenames.Count); name = $l.name }) }
}

function Sorted($items) {
    $arr = @($items | Group-Object { "$($_.key)|$($_.lang)" } | ForEach-Object { $_.Group | Sort-Object primary | Select-Object -First 1 })
    [Array]::Sort($arr, [Comparison[object]] {
        param($a, $b)
        $c = [string]::CompareOrdinal($a.key, $b.key)
        if (-not $c) { $c = $a.primary - $b.primary }
        if (-not $c) { $c = $a.spread - $b.spread }
        if (-not $c) { $c = [string]::CompareOrdinal($a.name, $b.name) }
        $c
    })
    return $arr
}

function Patterns($name) {
    Read-Source $name | ForEach-Object { $_.TrimEnd("`r") } | Where-Object { $_ -match '^- ' } | ForEach-Object { Unquote $_.Substring(2) }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Generated by tools/gen_linguist.ps1 from github-linguist (MIT license). Do not edit.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("struct LinguistLanguage {")
[void]$sb.AppendLine("    const wchar_t* name;")
[void]$sb.AppendLine("    unsigned color;  // 0xRRGGBB")
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("struct LinguistKey {")
[void]$sb.AppendLine("    const wchar_t* key;")
[void]$sb.AppendLine("    unsigned short language;  // 65535: a language GitHub does not count (data, prose)")
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("static const LinguistLanguage kLinguistLanguages[] = {")
foreach ($n in $names) {
    $c = $langs[$n].color
    $hex = if ($c -match '^#([0-9A-Fa-f]{6})$') { "0x" + $Matches[1].ToUpper() } else { "0x8B949E" }
    [void]$sb.AppendLine("    { $(CString $n), $hex },")
}
[void]$sb.AppendLine("};")
foreach ($t in @(@("kLinguistExtensions", "lowercase, sorted; an ambiguous extension lists its likeliest language first", $extensions), @("kLinguistFilenames", "sorted", $filenames))) {
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("// $($t[1])")
    [void]$sb.AppendLine("static const LinguistKey $($t[0])[] = {")
    foreach ($e in (Sorted $t[2])) { [void]$sb.AppendLine("    { $(CString $e.key), $($e.lang) },") }
    [void]$sb.AppendLine("};")
}
foreach ($t in @(@("kLinguistVendored", "vendor.yml"), @("kLinguistDocumentation", "documentation.yml"))) {
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("// $($t[1]): regular expressions matched against the path, '/' separated")
    [void]$sb.AppendLine("static const wchar_t* const $($t[0])[] = {")
    foreach ($p in (Patterns $t[1])) { [void]$sb.AppendLine("    $(CString $p),") }
    [void]$sb.AppendLine("};")
}
[IO.File]::WriteAllText($out, $sb.ToString().Replace("`r`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
"{0}: {1} languages, {2} extensions, {3} filenames" -f (Resolve-Path $out), $names.Count, $extensions.Count, $filenames.Count
